-- Clear any previous run of this file.
-- Orders deliberately cannot be orphaned by deleting a customer — the
-- foreign key forbids it, so a real shop can never lose its sales history
-- by accident. That means removing demo data has to work inwards: the
-- rows that hang off an order first, then the orders, then the people.
SET @demo := 'SELECT customer_id FROM customers WHERE email LIKE ''%@%.test''';

DELETE h FROM order_status_history h
  JOIN orders o ON o.order_id = h.order_id
  JOIN customers c ON c.customer_id = o.customer_id
  WHERE c.email LIKE '%@%.test';

DELETE i FROM order_items i
  JOIN orders o ON o.order_id = i.order_id
  JOIN customers c ON c.customer_id = o.customer_id
  WHERE c.email LIKE '%@%.test';

DELETE o FROM orders o
  JOIN customers c ON c.customer_id = o.customer_id
  WHERE c.email LIKE '%@%.test';

DELETE e FROM events e
  JOIN customers c ON c.customer_id = e.customer_id
  WHERE c.email LIKE '%@%.test';

DELETE FROM customers WHERE email LIKE '%@%.test';


-- ============================================================
-- Timed deals: one product, one price, one window.
--
-- The shop already has promotions and they are not this. A coupon is a
-- code somebody types; it takes a percentage off a whole category, and
-- the customer has to know it exists before it is worth anything. A
-- deal is a price on a shelf -- this machine, RM2,499, until Sunday
-- night -- and nobody types anything to get it.
--
-- Two things follow, and together they are why this is a table of its
-- own rather than four more columns on coupons:
--
--   * a deal names a product; a coupon names a category.
--   * a deal has to be charged. A coupon comes off the order total at
--     the end, and place_order already does that. A deal changes what a
--     line costs, so the till has to know about it -- and once the till
--     knows, the struck-through price on the card is a picture of
--     something already true rather than a promise the browser is
--     making on its own.
--
-- The window is two moments and not a duration, because "ends Sunday
-- 23:59" survives a page being left open overnight and "six hours from
-- now" does not. The Deals page has until now run its countdown off a
-- timestamp it wrote into localStorage the first time anybody opened
-- it, which meant the flash sale ended at a different moment for every
-- visitor, and never ended at all for one who cleared their browser.
-- ============================================================

CREATE TABLE public.deals (
  deal_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     INTEGER NOT NULL REFERENCES public.products(product_id) ON DELETE CASCADE,
  discount_price NUMERIC(10,2) NOT NULL CHECK (discount_price > 0),
  start_time     TIMESTAMPTZ NOT NULL DEFAULT now(),
  end_time       TIMESTAMPTZ NOT NULL,
  is_active      SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- A deal that ends before it starts is not a deal anybody meant to
  -- create, and it is the shape a mistyped date takes.
  CONSTRAINT deal_window_forwards CHECK (end_time > start_time)
);

CREATE INDEX idx_deal_product ON public.deals (product_id);
CREATE INDEX idx_deal_window  ON public.deals (start_time, end_time);


-- ------------------------------------------------------------
-- Two deals on one product at one moment.
--
-- Nothing here forbids it. The alternative was an exclusion constraint
-- over the time range, which would make the overlap an error at the
-- moment of creation -- correct, and it turns a staff member extending
-- a sale by a day into a failure they have to unpick.
--
-- So overlapping is allowed and answered instead: everything that reads
-- a price takes the lowest live one. That is the answer the customer
-- would argue for, and it is the same answer in the view, in the till
-- and on the card, because all three go through the definitions below.
-- ------------------------------------------------------------
ALTER TABLE public.deals ENABLE ROW LEVEL SECURITY;

-- Switched off, not started, or finished is filtered here, so the Deals
-- page does not have to be trusted to filter it in the browser -- the
-- same reasoning as "live promotions are public" on coupons.
CREATE POLICY "live deals are public" ON public.deals
  FOR SELECT TO anon, authenticated USING (
    is_active = 1
    AND start_time <= now()
    AND end_time > now()
  );

CREATE POLICY "staff manage deals" ON public.deals
  FOR ALL TO authenticated
  USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));

-- Supabase hands GRANT ALL to anon and authenticated on every table as
-- it is created. The policies above already refuse anon a write, but
-- the grants should not read as though it were allowed.
REVOKE ALL ON public.deals FROM anon, authenticated;
GRANT SELECT ON public.deals TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.deals TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.deals_deal_id_seq TO authenticated;


-- ============================================================
-- What the shop front reads: at most one deal per product, the cheapest
-- of whatever is running.
--
-- The window is written out here as well as in the policy. It is not
-- redundant: a signed-in member of staff carries "staff manage deals",
-- which returns every row including the finished ones, and without this
-- WHERE the shop would show an admin a sale that ended last week.
-- ============================================================
CREATE VIEW public.live_deals WITH (security_invoker = on) AS
SELECT DISTINCT ON (d.product_id)
  d.deal_id,
  d.product_id,
  d.discount_price,
  d.start_time,
  d.end_time
FROM public.deals d
WHERE d.is_active = 1
  AND d.start_time <= now()
  AND d.end_time > now()
ORDER BY d.product_id, d.discount_price ASC, d.end_time DESC;

REVOKE ALL ON public.live_deals FROM anon, authenticated;
GRANT SELECT ON public.live_deals TO anon, authenticated;


-- ============================================================
-- What the admin panel reads: every deal, live or not, with the product
-- it is on and what it saves.
-- ============================================================
CREATE VIEW public.admin_deals WITH (security_invoker = on) AS
SELECT
  d.deal_id,
  d.product_id,
  d.discount_price,
  d.start_time,
  d.end_time,
  d.is_active,
  d.created_at,
  p.name  AS product_name,
  p.price AS original_price,
  round((p.price - d.discount_price) / NULLIF(p.price, 0) * 100, 1) AS percent_off,
  (d.is_active = 1 AND d.start_time <= now() AND d.end_time > now()) AS is_live
FROM public.deals d
JOIN public.products p ON p.product_id = d.product_id;

REVOKE ALL ON public.admin_deals FROM anon, authenticated;
GRANT SELECT ON public.admin_deals TO authenticated;


-- ============================================================
-- The till.
--
-- Same function as before with one change, in two places: the price of
-- a line is now the lower of the product's price and any live deal on
-- it, instead of the product's price.
--
-- LEAST does the whole job on its own. It ignores NULL, so
-- LEAST(p.price, <no deal>) is p.price and no COALESCE is needed -- and
-- it also settles the case of a "deal" typed in above list price, which
-- is a fat finger rather than an offer and should not charge the
-- customer more than the shelf does.
--
-- What gets written down is what was charged. order_items.unit_price
-- and orders.subtotal hold the deal price, not the list price with the
-- saving noted beside it, for the same reason product_name is copied
-- into the row: an order has to read correctly years later, and by then
-- the deal will have been deleted.
--
-- A coupon still comes off after this, so a code stacks on top of a
-- deal price. That is a decision and not an accident: the shop has one
-- discount box, and a customer who is told 10% off and gets 10% off the
-- number they are looking at has been told the truth.
-- ============================================================
create or replace function public.place_order(
  p_name text,
  p_phone text,
  p_address text,
  p_coupon text default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
DECLARE
  v_customer integer := public.current_customer_id();
  v_name     text    := btrim(COALESCE(p_name, ''));
  v_phone    text    := btrim(COALESCE(p_phone, ''));
  v_address  text    := btrim(COALESCE(p_address, ''));
  v_code     text    := upper(btrim(COALESCE(p_coupon, '')));
  v_percent  numeric := 0;
  v_applied  text    := NULL;
  v_subtotal numeric := 0;
  v_discount numeric := 0;
  v_total    numeric := 0;
  v_order_id integer;
  v_lines    integer;
BEGIN
  IF v_customer IS NULL THEN
    RAISE EXCEPTION 'Please log in first.' USING ERRCODE = '42501';
  END IF;

  IF v_name = '' OR v_address = '' THEN
    RAISE EXCEPTION 'Please fill in your delivery details.' USING ERRCODE = 'P0001';
  END IF;

  -- One line is still one line however many upgrades hang off it, so
  -- COUNT(*) counts cart_items and the upgrades only reach the money.
  --
  -- The deal is read here, not sent up from the phone. This function is
  -- SECURITY DEFINER and so is not subject to the policy on deals, which
  -- is why the window is spelled out again in the subquery.
  SELECT COUNT(*),
         COALESCE(SUM((LEAST(p.price, dl.discount_price) + COALESCE(x.extra, 0)) * c.quantity), 0)
    INTO v_lines, v_subtotal
  FROM public.cart_items c
  JOIN public.products p ON p.product_id = c.product_id
  LEFT JOIN LATERAL (
    SELECT MIN(d.discount_price) AS discount_price
    FROM public.deals d
    WHERE d.product_id = c.product_id
      AND d.is_active = 1
      AND d.start_time <= now()
      AND d.end_time > now()
  ) dl ON true
  LEFT JOIN LATERAL (
    SELECT SUM(pu.price_delta) AS extra
    FROM public.cart_item_upgrades ciu
    JOIN public.prebuilt_upgrades pu ON pu.upgrade_id = ciu.upgrade_id
    WHERE ciu.customer_id = c.customer_id
      AND ciu.product_id  = c.product_id
  ) x ON true
  WHERE c.customer_id = v_customer;

  IF v_lines = 0 THEN
    RAISE EXCEPTION 'Your cart is empty.' USING ERRCODE = 'P0001';
  END IF;

  IF v_code <> '' THEN
    SELECT co.code, co.discount_percent INTO v_applied, v_percent
    FROM public.coupons co
    WHERE co.code = v_code
      AND co.is_active = 1
      AND co.starts_at <= now()
      AND (co.ends_at IS NULL OR co.ends_at >= now());

    IF NOT FOUND THEN
      v_applied := NULL;
      v_percent := 0;
    END IF;
  END IF;

  v_discount := round(v_subtotal * v_percent / 100, 2);
  v_total    := v_subtotal - v_discount;

  INSERT INTO public.orders
    (customer_id, subtotal, discount, total, coupon_code,
     shipping_name, shipping_phone, shipping_address)
  VALUES
    (v_customer, v_subtotal, v_discount, v_total, v_applied,
     v_name, NULLIF(v_phone, ''), v_address)
  RETURNING order_id INTO v_order_id;

  -- The machines and everything else, at the price they were sold for.
  INSERT INTO public.order_items
    (order_id, product_id, product_name, unit_price, quantity, line_total)
  SELECT v_order_id,
         p.product_id,
         p.name,
         LEAST(p.price, dl.discount_price),
         c.quantity,
         LEAST(p.price, dl.discount_price) * c.quantity
  FROM public.cart_items c
  JOIN public.products p ON p.product_id = c.product_id
  LEFT JOIN LATERAL (
    SELECT MIN(d.discount_price) AS discount_price
    FROM public.deals d
    WHERE d.product_id = c.product_id
      AND d.is_active = 1
      AND d.start_time <= now()
      AND d.end_time > now()
  ) dl ON true
  WHERE c.customer_id = v_customer;

  -- The upgrades, one line each, named so an invoice reads properly.
  -- A deal is on the machine, not on the option bolted to it, so these
  -- are untouched.
  INSERT INTO public.order_items
    (order_id, product_id, product_name, unit_price, quantity, line_total)
  SELECT v_order_id,
         NULL,
         p.name || ' + ' || pu.label,
         pu.price_delta,
         c.quantity,
         pu.price_delta * c.quantity
  FROM public.cart_items c
  JOIN public.products p ON p.product_id = c.product_id
  JOIN public.cart_item_upgrades ciu
    ON ciu.customer_id = c.customer_id
   AND ciu.product_id  = c.product_id
  JOIN public.prebuilt_upgrades pu ON pu.upgrade_id = ciu.upgrade_id
  WHERE c.customer_id = v_customer;

  INSERT INTO public.events (customer_id, product_id, event_type)
  SELECT v_customer, c.product_id, 'purchase'
  FROM public.cart_items c
  WHERE c.customer_id = v_customer;

  -- cart_item_upgrades is keyed on the basket line and cascades, so the
  -- ticks go with it.
  DELETE FROM public.cart_items WHERE customer_id = v_customer;

  RETURN jsonb_build_object(
    'orderId',  v_order_id,
    'subtotal', v_subtotal,
    'discount', v_discount,
    'total',    v_total,
    'coupon',   v_applied
  );
END;
$function$;

-- create or replace keeps the grants that were already on the function,
-- but not if the signature ever changes. It has not changed here; these
-- are restated so this file stands on its own.
REVOKE EXECUTE ON FUNCTION public.place_order(text, text, text, text) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.place_order(text, text, text, text) TO authenticated;

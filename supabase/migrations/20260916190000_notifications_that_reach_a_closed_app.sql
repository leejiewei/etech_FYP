-- ============================================================
-- Notifications that reach a phone with the app shut.
--
-- The bell already works and has since 11 September: staff approve a
-- payment or move an order, the database writes a row to notifications
-- inside the same transaction, and Realtime hands it to whoever is
-- subscribed. The catch is in that last word. A Realtime subscription is
-- a websocket held open by a running app, so the customer who closed the
-- app -- which is every customer, most of the time -- finds out when they
-- next open it. Which is the thing they were trying not to have to do.
--
-- Reaching a closed Android app means Firebase Cloud Messaging. There is
-- no way round that; the OS will not let an app wake itself.
--
-- So: every notification row now also fans out to the customer's
-- registered phones through an Edge Function that talks to FCM. The row
-- is still the record. The push is a copy of it shouted at a device, and
-- if the shouting fails the row is still there and the bell still shows
-- it next time the app opens. That ordering matters -- push is famously
-- lossy, and nothing in this shop should depend on it having arrived.
--
-- ------------------------------------------------------------
-- Why the trigger posts an id and nothing else
--
-- net.http_post() writes its payload into a queue table in this database
-- and its response into another, both of which persist. Putting the
-- notification's title and body in that payload would copy a customer's
-- order news into a third place nobody thinks of as holding it. The
-- trigger sends the notification_id; the function reads the row itself
-- with its own service-role key and posts it straight to Google.
-- ------------------------------------------------------------
-- ============================================================

-- The extension that lets a trigger make an outbound HTTP call. Without
-- it a trigger can only touch this database.
-- pg_net is not relocatable: it puts its functions in a schema called
-- `net` whatever you ask for, which is why the call below is
-- net.http_post and not extensions.something.
CREATE EXTENSION IF NOT EXISTS pg_net;


-- ------------------------------------------------------------
-- 1. Which phones belong to whom
--
-- One row per installation, not per customer: a person with a phone and
-- a tablet should be told on both.
--
-- The token is unique across the whole table, and that is the important
-- constraint. An FCM token identifies an *install*, not a person, so when
-- a second customer signs in on the same handset the token has to move to
-- them rather than sit under both -- otherwise the first customer keeps
-- receiving the second's order news on a phone they no longer hold.
-- register_device_token() below relies on this to do exactly that.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.device_tokens (
  device_token_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     integer NOT NULL REFERENCES public.customers(customer_id) ON DELETE CASCADE,
  token           text    NOT NULL UNIQUE,
  platform        text    NOT NULL DEFAULT 'android'
                          CHECK (platform IN ('android', 'ios', 'web')),
  created_at      timestamptz NOT NULL DEFAULT now(),
  -- Bumped every time the app hands the same token back, so a token that
  -- has not been seen for months can be recognised as dead weight later.
  last_seen_at    timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_device_token_customer
  ON public.device_tokens (customer_id);

ALTER TABLE public.device_tokens ENABLE ROW LEVEL SECURITY;

-- Nothing is granted to anybody. Rows go in and out through the two
-- SECURITY DEFINER functions below, and are read only by the Edge
-- Function using the service role, which RLS does not apply to.
--
-- A customer holding SELECT here would be able to read a token and, with
-- it, ask for pushes meant for somebody else. There is no reason for a
-- client to read this table at all, so it cannot.
REVOKE ALL ON public.device_tokens FROM anon, authenticated, public;


-- ------------------------------------------------------------
-- 2. Registering and forgetting a phone
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.register_device_token(
  p_token    text,
  p_platform text DEFAULT 'android'
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_customer integer := public.current_customer_id();
  v_token    text    := btrim(COALESCE(p_token, ''));
BEGIN
  IF v_customer IS NULL THEN
    RAISE EXCEPTION 'Please log in first.' USING ERRCODE = '42501';
  END IF;

  IF v_token = '' THEN
    RAISE EXCEPTION 'No device token given.' USING ERRCODE = 'P0001';
  END IF;

  -- ON CONFLICT on the token, not on (customer, token): a handset that
  -- has changed hands must end up under its current owner and only
  -- there. This is the line that stops one customer's phone buzzing with
  -- another customer's orders.
  INSERT INTO public.device_tokens (customer_id, token, platform)
  VALUES (v_customer, v_token,
          CASE WHEN lower(COALESCE(p_platform, '')) IN ('android', 'ios', 'web')
               THEN lower(p_platform) ELSE 'android' END)
  ON CONFLICT (token) DO UPDATE
    SET customer_id  = EXCLUDED.customer_id,
        platform     = EXCLUDED.platform,
        last_seen_at = now();
END;
$$;

REVOKE EXECUTE ON FUNCTION public.register_device_token(text, text) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.register_device_token(text, text) TO authenticated;


-- Signing out. Deliberately keyed on the token alone and not on the
-- caller: the point of pressing sign-out is that this handset should stop
-- receiving that person's news, and by the time the app gets round to
-- calling this the session may already be gone.
CREATE OR REPLACE FUNCTION public.forget_device_token(p_token text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  DELETE FROM public.device_tokens WHERE token = btrim(COALESCE(p_token, ''));
END;
$$;

REVOKE EXECUTE ON FUNCTION public.forget_device_token(text) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.forget_device_token(text) TO authenticated;


-- ------------------------------------------------------------
-- 3. Where to shout, and with what credentials
--
-- Both live in Vault rather than in this file, because this file is in a
-- public git repository and one of them is the service-role key. The
-- trigger looks them up by name; setting them is a separate act, done
-- once, and documented in docs/PUSH_SETUP.md.
--
-- If either is missing the trigger does nothing at all and says so in the
-- log. That is the correct failure: a shop without push configured should
-- still be able to take an order, and an exception here would roll back
-- the staff action that caused it.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.push_secret(p_name text)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name = p_name LIMIT 1;
$$;

REVOKE EXECUTE ON FUNCTION public.push_secret(text) FROM public, anon, authenticated;


CREATE OR REPLACE FUNCTION public.notify_push()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_url text := public.push_secret('push_function_url');
  v_key text := public.push_secret('push_service_key');
BEGIN
  IF v_url IS NULL OR v_key IS NULL THEN
    RAISE LOG 'notify_push: push not configured, skipping notification %',
      NEW.notification_id;
    RETURN NEW;
  END IF;

  -- Fire and forget. net.http_post queues the request and returns
  -- immediately, so a slow or unreachable Google does not hold open the
  -- transaction that a member of staff is waiting on.
  PERFORM net.http_post(
    url     := v_url,
    headers := jsonb_build_object(
                 'Content-Type',  'application/json',
                 'Authorization', 'Bearer ' || v_key),
    body    := jsonb_build_object('notification_id', NEW.notification_id),
    timeout_milliseconds := 5000
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_notify_push ON public.notifications;

-- AFTER INSERT, so a failure to queue the push cannot take the
-- notification row down with it.
CREATE TRIGGER trg_notify_push
AFTER INSERT ON public.notifications
FOR EACH ROW EXECUTE FUNCTION public.notify_push();

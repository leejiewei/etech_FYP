-- ============================================================
-- Telling the customer when staff move their order.
--
-- Until now the customer found out their payment had been approved, or
-- their parcel had left, by opening Order History and looking. Staff
-- could send a WhatsApp from the Orders page, but that is a button
-- somebody has to remember to press, and the Reject button's own
-- confirmation already promised "the customer will be asked to send
-- another receipt" -- which nothing actually did.
--
-- So the two functions staff use to move an order now leave a message
-- for the customer at the same moment, in the same transaction. Three
-- moments are worth a message:
--
--   payment_approved   the money has been checked and accepted
--   payment_rejected   the receipt did not match; they have to act
--   order_shipped      the parcel has left
--
-- Pending -> Processing is not one of them on its own: it happens as a
-- side effect of approving the payment, and that message already says so.
--
-- The website and the app both read this table and both subscribe to it
-- through Realtime, so a customer with either open sees the message
-- arrive without reloading.
--
-- Written from inside the two functions rather than by a trigger on
-- orders, so every row here has a member of staff's deliberate action
-- behind it, and a status fixed by hand in the SQL editor does not ping
-- somebody's phone.
-- ============================================================

CREATE TABLE public.notifications (
  notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id     INTEGER NOT NULL REFERENCES public.customers(customer_id) ON DELETE CASCADE,
  order_id        INTEGER NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
  kind            VARCHAR(30) NOT NULL
                  CHECK (kind IN ('payment_approved', 'payment_rejected', 'order_shipped')),
  title           VARCHAR(120) NOT NULL,
  body            TEXT NOT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- NULL until the customer has seen it. One timestamp rather than a
  -- flag, because "when did they read it" costs nothing extra to keep.
  read_at         TIMESTAMPTZ NULL
);

-- The only question ever asked of this table: this customer's newest.
CREATE INDEX idx_notification_customer ON public.notifications (customer_id, created_at DESC);
CREATE INDEX idx_notification_order    ON public.notifications (order_id);

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Read-only to the customer, and only their own. Realtime applies this
-- same policy before it hands a new row to a subscriber, which is what
-- stops one customer's app hearing about another customer's parcel.
CREATE POLICY "own notifications" ON public.notifications
  FOR SELECT TO authenticated
  USING (customer_id = (SELECT public.current_customer_id()));

-- Nothing is granted but SELECT. Rows are written by the two SECURITY
-- DEFINER functions below; marking one read goes through its own
-- function, so a customer never holds UPDATE on the table and cannot
-- rewrite what the shop told them.
REVOKE ALL ON public.notifications FROM anon, authenticated;
GRANT SELECT ON public.notifications TO authenticated;

-- Without this Realtime never sees the inserts at all.
ALTER PUBLICATION supabase_realtime ADD TABLE public.notifications;


-- ============================================================
-- Marking messages read.
--
-- With no ids, everything of the caller's that is unread -- which is
-- what opening the bell means. The customer is read from the session;
-- ids belonging to anybody else simply match nothing.
-- ============================================================
CREATE OR REPLACE FUNCTION public.mark_notifications_read(p_ids integer[] DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_customer integer := public.current_customer_id();
  v_count    integer;
BEGIN
  IF v_customer IS NULL THEN
    RAISE EXCEPTION 'Please log in first.' USING ERRCODE = '42501';
  END IF;

  UPDATE public.notifications
  SET read_at = now()
  WHERE customer_id = v_customer
    AND read_at IS NULL
    AND (p_ids IS NULL OR notification_id = ANY (p_ids));

  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.mark_notifications_read(integer[]) FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.mark_notifications_read(integer[]) TO authenticated;


-- ============================================================
-- Moving an order along, now with a message when it ships.
--
-- The version from 20260827114759_admin_views.sql, with two additions:
-- the status before the change is read first, and a move *into* Shipped
-- leaves a message. Setting Shipped on an order that was already Shipped
-- -- the dropdown allows it -- does not send the same news twice.
--
-- The staff note is deliberately not copied into the message. It has
-- only ever been written for other staff to read in the history line.
-- ============================================================
CREATE OR REPLACE FUNCTION public.admin_set_order_status(
  p_order_id integer,
  p_status   public.order_status,
  p_note     text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_admin    integer;
  v_before   public.order_status;
  v_customer integer;
BEGIN
  SELECT a.admin_id INTO v_admin
  FROM public.admins a WHERE a.auth_user_id = auth.uid();

  IF v_admin IS NULL THEN
    RAISE EXCEPTION 'Staff access only.' USING ERRCODE = '42501';
  END IF;

  -- FOR UPDATE so two members of staff pressing Ship at once cannot both
  -- read "Processing" and both send the message.
  SELECT o.status, o.customer_id INTO v_before, v_customer
  FROM public.orders o WHERE o.order_id = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'That order no longer exists.' USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.orders SET status = p_status WHERE order_id = p_order_id;

  INSERT INTO public.order_status_history (order_id, status, changed_by, note)
  VALUES (p_order_id, p_status, v_admin, NULLIF(btrim(COALESCE(p_note, '')), ''));

  IF p_status = 'Shipped' AND v_before IS DISTINCT FROM 'Shipped' THEN
    INSERT INTO public.notifications (customer_id, order_id, kind, title, body)
    VALUES (v_customer, p_order_id, 'order_shipped',
            'Your order is on its way',
            'Order #' || p_order_id || ' has been shipped.');
  END IF;
END;
$$;


-- ============================================================
-- Staff saying yes or no to a payment, now with a message either way.
--
-- The version from 20260908020000_manual_payment_verification.sql, with
-- the previous payment status read first so that pressing Approve on a
-- payment that is already approved does not message anybody.
--
-- A rejection gets a message as well as an approval, and it is arguably
-- the more important of the two: it is the only one of the three where
-- the customer has to do something.
-- ============================================================
CREATE OR REPLACE FUNCTION public.admin_set_payment_status(
  p_order_id integer,
  p_status   public.payment_status,
  p_note     text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_admin    integer;
  v_status   public.order_status;
  v_before   public.payment_status;
  v_customer integer;
BEGIN
  SELECT a.admin_id INTO v_admin
  FROM public.admins a WHERE a.auth_user_id = auth.uid();

  IF v_admin IS NULL THEN
    RAISE EXCEPTION 'Staff access only.' USING ERRCODE = '42501';
  END IF;

  SELECT o.payment_status, o.status, o.customer_id INTO v_before, v_status, v_customer
  FROM public.orders o WHERE o.order_id = p_order_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'That order no longer exists.' USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.orders SET payment_status = p_status WHERE order_id = p_order_id;

  IF p_status = 'APPROVED' AND v_status = 'Pending' THEN
    UPDATE public.orders SET status = 'Processing' WHERE order_id = p_order_id;

    INSERT INTO public.order_status_history (order_id, status, changed_by, note)
    VALUES (p_order_id, 'Processing', v_admin,
            COALESCE(NULLIF(btrim(COALESCE(p_note, '')), ''), 'Payment approved'));
  ELSE
    INSERT INTO public.order_status_history (order_id, status, changed_by, note)
    VALUES (p_order_id, v_status, v_admin,
            COALESCE(NULLIF(btrim(COALESCE(p_note, '')), ''),
                     'Payment ' || lower(p_status::text)));
  END IF;

  IF p_status IS DISTINCT FROM v_before THEN
    IF p_status = 'APPROVED' THEN
      INSERT INTO public.notifications (customer_id, order_id, kind, title, body)
      VALUES (v_customer, p_order_id, 'payment_approved',
              'Payment received',
              'We have confirmed your payment for order #' || p_order_id ||
              CASE WHEN v_status = 'Pending'
                   THEN '. We are preparing it now.'
                   ELSE '.' END);
    ELSIF p_status = 'REJECTED' THEN
      INSERT INTO public.notifications (customer_id, order_id, kind, title, body)
      VALUES (v_customer, p_order_id, 'payment_rejected',
              'Please send another receipt',
              'We could not match your receipt to order #' || p_order_id ||
              '. Please upload a clear photo showing the amount and the date.');
    END IF;
  END IF;
END;
$$;

-- ============================================================
-- Security hardening: account lockout, an audit trail, and the
-- privileges the earlier migrations meant to leave behind.
--
-- Three separate jobs in one file because they are one review:
--
--   1. login_attempts stops being a leftover from MySQL and becomes the
--      table behind a real, enforced account lockout.
--   2. security_events gives the shop somewhere to write down the things
--      it would want to look at after an incident.
--   3. The Security Advisor's remaining findings are either fixed or
--      given a reason in writing for being left alone.
-- ============================================================


-- ============================================================
-- 1.  THE AUDIT TRAIL
--
-- Written first because the lockout in section 2 logs to it.
--
-- The shop already records what customers do -- events, chatbot_logs,
-- search_logs -- and none of it is any use after a break-in. Those
-- tables answer "what is selling"; nothing answers "who changed that
-- price", "when did this account start being guessed at", or "was
-- anyone signed in as staff at 3am".
--
-- Kept deliberately small. An audit table nobody reads is a liability
-- rather than a control, so this records the handful of things that
-- would actually be looked at afterwards: sign-in failures and
-- lockouts, changes to who is staff, changes to a price or an order's
-- status, and coupon changes. Browsing is already in events and is not
-- security.
--
-- WHO CAN WRITE TO IT
--
-- Nobody, directly. There is no INSERT policy and no INSERT grant for
-- any client role. Rows arrive only from SECURITY DEFINER functions and
-- triggers inside the database, which is what makes the trail worth
-- reading: a client that could write here could also write a false
-- entry, or flood the table until the real one scrolled off.
-- ============================================================

CREATE TABLE public.security_events (
  event_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),

  -- Dotted, coarse to fine: auth.password_failed, admin.role_granted,
  -- catalogue.price_changed. Text rather than an enum so adding a kind
  -- later is not a migration on a table that must never be locked.
  kind        text        NOT NULL,

  -- Who caused it, where each is known. actor_user_id is the auth user;
  -- subject_user_id is the account it happened *to*, which for a lockout
  -- is the same and for a role grant is not.
  actor_user_id   uuid,
  subject_user_id uuid,

  -- Anything specific to the kind. Deliberately jsonb: the alternative
  -- is twenty nullable columns, nineteen of them empty on every row.
  detail      jsonb       NOT NULL DEFAULT '{}'::jsonb
);

COMMENT ON TABLE public.security_events IS
  'Append-only security audit trail. Written only by SECURITY DEFINER '
  'functions and triggers; readable by staff; never writable by a client.';

CREATE INDEX idx_security_events_time ON public.security_events (occurred_at DESC);
CREATE INDEX idx_security_events_kind ON public.security_events (kind, occurred_at DESC);

ALTER TABLE public.security_events ENABLE ROW LEVEL SECURITY;

-- Staff read it. Nobody writes it, updates it or deletes it through the
-- API -- the absence of those policies is the control, not an oversight.
CREATE POLICY "staff read the security log" ON public.security_events
  FOR SELECT TO authenticated
  USING ((SELECT public.is_admin()));

REVOKE ALL ON public.security_events FROM anon, authenticated;
GRANT SELECT ON public.security_events TO authenticated;


-- ------------------------------------------------------------
-- The only way a row gets in.
--
-- SECURITY DEFINER so the triggers and the auth hook can write while
-- every client role is revoked. Note the EXECUTE grants at the bottom of
-- this block: anon and authenticated are not among them, so this cannot
-- be called over /rest/v1/rpc/ to forge an entry.
--
-- Swallows its own errors on purpose. Logging is a side effect of the
-- statement that triggered it, and a failure to write the log must not
-- roll back a price change, a sign-in or an order. A trail with a hole
-- in it beats a shop that stops working.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.log_security_event(
  p_kind    text,
  p_subject uuid   DEFAULT NULL,
  p_detail  jsonb  DEFAULT '{}'::jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  INSERT INTO public.security_events (kind, actor_user_id, subject_user_id, detail)
  VALUES (p_kind, auth.uid(), p_subject, COALESCE(p_detail, '{}'::jsonb));
EXCEPTION WHEN OTHERS THEN
  RAISE WARNING 'log_security_event(%) failed: %', p_kind, SQLERRM;
END;
$function$;

REVOKE EXECUTE ON FUNCTION public.log_security_event(text, uuid, jsonb) FROM public, anon, authenticated;


-- ============================================================
-- 2.  LOCKING AN ACCOUNT AFTER REPEATED FAILURES
--
-- login_attempts arrived from the MySQL schema and has never been
-- written to since. It was read by login.php, which counted failures for
-- a username and refused to check the password once there were five.
-- With PHP gone, nothing counts anything: the staff sign-in page says so
-- in a comment and leaves it to Supabase Auth's own per-IP rate limit,
-- which is 30 sign-in requests per five minutes per address.
--
-- A per-IP limit is not an account lockout. Thirty guesses every five
-- minutes is over eight thousand a day from a single address, and there
-- is no shortage of addresses; more to the point the limit is
-- indifferent to which account is being guessed, so a slow, patient
-- attack on one admin password looks exactly like ordinary traffic.
--
-- WHY THIS IS A HOOK AND NOT A CHECK IN THE PAGE
--
-- The obvious version -- have the login page ask the database whether
-- this account is locked before calling signInWithPassword -- is worth
-- nothing at all. The browser is the attacker's own code. They would
-- call Supabase Auth directly and never ask.
--
-- Supabase Auth can be made to ask instead. The password verification
-- hook runs inside Auth, on every password check, before Auth answers;
-- a decision returned from here is one no client can skip. It is the
-- only place on this stack where a lockout can actually be enforced.
--
-- POLICY
--
--   5 failures inside 15 minutes  ->  locked for 15 minutes
--   a successful sign-in          ->  the count is cleared
--
-- Chosen to hurt a script and not a person. A guessing run drops to
-- twenty attempts an hour, while somebody who has genuinely mistyped
-- their password five times has time to go and find it. Nothing here is
-- permanent: a lockout that needs staff to lift it is a way of locking
-- the shop's own owner out of the shop on a Saturday.
--
-- The table is keyed on the auth user id, which is the only identifier
-- the hook is given -- and the right one, because it means the lock
-- follows the account rather than the address or the spelling of the
-- email.
--
-- TO TURN IT ON, which this migration cannot do by itself:
--   Dashboard -> Authentication -> Hooks -> Password Verification Attempt
--   -> Postgres -> public.hook_password_verification_attempt
-- (or uncomment [auth.hook.password_verification_attempt] in
--  supabase/config.toml for a local stack). Until that is done the
--  function is inert and sign-in behaves exactly as it does today.
-- ============================================================

-- The old shape (username / ip_address / attempted_at) was never used
-- and the table has always been empty -- confirmed in
-- 20260826032554_etech_sequences.sql -- so it is replaced rather than
-- migrated.
DROP TABLE IF EXISTS public.login_attempts;

CREATE TABLE public.login_attempts (
  -- auth.users.id. No foreign key: auth is a separate schema and a
  -- deleted user should not be able to block its own deletion.
  user_id          uuid PRIMARY KEY,
  failures         integer     NOT NULL DEFAULT 0,
  first_failure_at timestamptz NOT NULL DEFAULT now(),
  last_failure_at  timestamptz NOT NULL DEFAULT now(),
  locked_until     timestamptz
);

COMMENT ON TABLE public.login_attempts IS
  'Failed password attempts per auth user, written only by the password '
  'verification hook. No client role may read or write it.';

CREATE INDEX idx_login_attempts_locked ON public.login_attempts (locked_until)
  WHERE locked_until IS NOT NULL;

ALTER TABLE public.login_attempts ENABLE ROW LEVEL SECURITY;

-- RLS enabled with no policy means "nobody, by any route that respects
-- RLS", which is exactly the intent. This is why the Security Advisor's
-- rls_enabled_no_policy note on this table is the expected state and not
-- a gap. Auth reaches the table as supabase_auth_admin, which owns the
-- grants below and is not subject to policies.
REVOKE ALL ON public.login_attempts FROM anon, authenticated, public;


-- ------------------------------------------------------------
-- The hook.
--
-- Supabase Auth calls this on every password check with
--   { user_id: uuid, valid: boolean }
-- and reads back either
--   { decision: 'continue' }             -- let Auth carry on as normal
--   { error: { http_code, message } }    -- refuse
--
-- Order matters. The lock is tested before `valid` is looked at, so a
-- locked account stays locked even when the attacker finally guesses
-- correctly -- otherwise the lockout would stop applying at the exact
-- moment it matters.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.hook_password_verification_attempt(event jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_user_id uuid    := NULLIF(event ->> 'user_id', '')::uuid;
  v_valid   boolean := COALESCE((event ->> 'valid')::boolean, false);
  v_row     public.login_attempts%ROWTYPE;

  c_max_failures constant integer  := 5;
  c_window       constant interval := interval '15 minutes';
  c_lockout      constant interval := interval '15 minutes';
BEGIN
  IF v_user_id IS NULL THEN
    RETURN jsonb_build_object('decision', 'continue');
  END IF;

  SELECT * INTO v_row FROM public.login_attempts WHERE user_id = v_user_id;

  -- Inside a live lockout: refuse, whatever the password was.
  IF v_row.locked_until IS NOT NULL AND v_row.locked_until > now() THEN
    RETURN jsonb_build_object(
      'error', jsonb_build_object(
        'http_code', 429,
        'message',   'Too many failed sign-in attempts. Please try again in a few minutes.'
      )
    );
  END IF;

  -- Right password, not locked. Clear the slate.
  IF v_valid THEN
    DELETE FROM public.login_attempts WHERE user_id = v_user_id;
    RETURN jsonb_build_object('decision', 'continue');
  END IF;

  -- A failure. Count it, restarting the count when the previous one was
  -- long enough ago that this is a fresh episode rather than a run.
  INSERT INTO public.login_attempts AS la
    (user_id, failures, first_failure_at, last_failure_at, locked_until)
  VALUES (v_user_id, 1, now(), now(), NULL)
  ON CONFLICT (user_id) DO UPDATE
    SET failures = CASE
                     WHEN la.last_failure_at < now() - c_window THEN 1
                     ELSE la.failures + 1
                   END,
        first_failure_at = CASE
                             WHEN la.last_failure_at < now() - c_window THEN now()
                             ELSE la.first_failure_at
                           END,
        last_failure_at = now(),
        locked_until = NULL
  RETURNING * INTO v_row;

  IF v_row.failures >= c_max_failures THEN
    UPDATE public.login_attempts
       SET locked_until = now() + c_lockout
     WHERE user_id = v_user_id;

    PERFORM public.log_security_event(
      'auth.account_locked',
      v_user_id,
      jsonb_build_object('failures', v_row.failures, 'locked_for', c_lockout::text)
    );

    RETURN jsonb_build_object(
      'error', jsonb_build_object(
        'http_code', 429,
        'message',   'Too many failed sign-in attempts. Please try again in a few minutes.'
      )
    );
  END IF;

  PERFORM public.log_security_event(
    'auth.password_failed',
    v_user_id,
    jsonb_build_object('failures', v_row.failures)
  );

  -- Let Auth give its own "incorrect email or password", which is the
  -- same answer it gives for an address that does not exist. Saying
  -- "wrong password" from here would turn this hook into the enumeration
  -- oracle that web/js/auth.js was just changed to close.
  RETURN jsonb_build_object('decision', 'continue');
END;
$function$;

-- Auth calls the hook as supabase_auth_admin and as nobody else.
GRANT USAGE ON SCHEMA public TO supabase_auth_admin;
GRANT EXECUTE ON FUNCTION public.hook_password_verification_attempt(jsonb)
  TO supabase_auth_admin;
GRANT EXECUTE ON FUNCTION public.log_security_event(text, uuid, jsonb)
  TO supabase_auth_admin;
GRANT ALL ON TABLE public.login_attempts TO supabase_auth_admin;
GRANT INSERT ON TABLE public.security_events TO supabase_auth_admin;
GRANT USAGE, SELECT ON SEQUENCE public.security_events_event_id_seq TO supabase_auth_admin;

REVOKE EXECUTE ON FUNCTION public.hook_password_verification_attempt(jsonb)
  FROM public, anon, authenticated;


-- ============================================================
-- 3.  WHAT GETS WRITTEN DOWN
--
-- Triggers rather than calls added to each function, for the same reason
-- the audit table has no INSERT policy: a trigger cannot be gone round.
-- Somebody who found a way to change a price by another route would
-- still be logged.
--
-- AFTER triggers throughout, so nothing here can fail a write.
-- ============================================================

-- ---------------------------------------------------- who is staff
-- The highest-value change in the database. Anyone in admins can read
-- every customer's address and every order.
CREATE OR REPLACE FUNCTION public.audit_admins_changed()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.log_security_event(
      'admin.role_granted', NEW.auth_user_id,
      jsonb_build_object('admin_id', NEW.admin_id, 'username', NEW.username));
  ELSIF TG_OP = 'DELETE' THEN
    PERFORM public.log_security_event(
      'admin.role_revoked', OLD.auth_user_id,
      jsonb_build_object('admin_id', OLD.admin_id, 'username', OLD.username));
  ELSE
    PERFORM public.log_security_event(
      'admin.record_changed', NEW.auth_user_id,
      jsonb_build_object('admin_id', NEW.admin_id, 'username', NEW.username));
  END IF;
  RETURN NULL;
END;
$function$;

CREATE TRIGGER trg_audit_admins
  AFTER INSERT OR UPDATE OR DELETE ON public.admins
  FOR EACH ROW EXECUTE FUNCTION public.audit_admins_changed();


-- ---------------------------------------------------- money
-- A price or an active flag changing is the catalogue edit worth being
-- able to reconstruct. Stock and description changes are ordinary work
-- and would drown the useful rows, so they are not recorded.
CREATE OR REPLACE FUNCTION public.audit_product_price_changed()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NEW.price IS DISTINCT FROM OLD.price THEN
    PERFORM public.log_security_event(
      'catalogue.price_changed', NULL,
      jsonb_build_object('product_id', NEW.product_id,
                         'from', OLD.price, 'to', NEW.price));
  END IF;

  IF NEW.is_active IS DISTINCT FROM OLD.is_active THEN
    PERFORM public.log_security_event(
      'catalogue.visibility_changed', NULL,
      jsonb_build_object('product_id', NEW.product_id,
                         'from', OLD.is_active, 'to', NEW.is_active));
  END IF;

  RETURN NULL;
END;
$function$;

CREATE TRIGGER trg_audit_product_price
  AFTER UPDATE ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.audit_product_price_changed();


-- ---------------------------------------------------- orders
-- Who moved an order, and to what. admin_set_order_status() already
-- writes order_status_history for the customer's benefit; this is the
-- same fact recorded where it cannot be edited by the panel.
CREATE OR REPLACE FUNCTION public.audit_order_status_changed()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    PERFORM public.log_security_event(
      'order.status_changed', NULL,
      -- status is an enum; jsonb_build_object has no mapping for one, so
      -- both sides are cast to text.
      jsonb_build_object('order_id', NEW.order_id,
                         'from', OLD.status::text, 'to', NEW.status::text));
  END IF;
  RETURN NULL;
END;
$function$;

CREATE TRIGGER trg_audit_order_status
  AFTER UPDATE ON public.orders
  FOR EACH ROW EXECUTE FUNCTION public.audit_order_status_changed();


-- ---------------------------------------------------- discounts
-- A coupon is money given away, and the one catalogue object a
-- compromised staff account would reach for first.
CREATE OR REPLACE FUNCTION public.audit_coupons_changed()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  -- NEW is unset on DELETE and OLD is unset on INSERT, and COALESCE over
  -- two record variables is not a safe way to say that, so the row is
  -- picked explicitly.
  v_row public.coupons%ROWTYPE;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_row := OLD;
  ELSE
    v_row := NEW;
  END IF;

  PERFORM public.log_security_event(
    'coupon.' || lower(TG_OP), NULL,
    jsonb_build_object('code', v_row.code,
                       'discount_percent', v_row.discount_percent,
                       'is_active', v_row.is_active));
  RETURN NULL;
END;
$function$;

CREATE TRIGGER trg_audit_coupons
  AFTER INSERT OR UPDATE OR DELETE ON public.coupons
  FOR EACH ROW EXECUTE FUNCTION public.audit_coupons_changed();


-- ============================================================
-- 4.  THE REST OF THE PRIVILEGE TIDY-UP
--
-- 20260828005426_revoke_anon_defaults.sql did this pass for the
-- functions that existed then. Four more have been added since, by the
-- prebuilt-PC work, and they arrived with Supabase's default EXECUTE
-- grant to anon and authenticated still attached.
--
-- Three of them are trigger functions. A trigger function needs no
-- EXECUTE grant at all -- Postgres runs it as part of the statement that
-- fired it -- so the grant does nothing except publish it at
-- /rest/v1/rpc/<name>, where anyone holding the publishable key can call
-- it directly. prebuilt_stock_follows_parts() and
-- prebuilt_parts_changed() called that way run with a null trigger
-- context; handle_new_auth_user() is worse, because it is the function
-- that decides who gets a customers row.
--
-- None of them is known to be exploitable. That is not the point: they
-- are reachable and they were never meant to be.
-- ============================================================

REVOKE EXECUTE ON FUNCTION public.handle_new_auth_user()
  FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.prebuilt_parts_changed()
  FROM public, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.prebuilt_stock_follows_parts()
  FROM public, anon, authenticated;

-- recompute_prebuilt_stock() is not a trigger function -- the admin
-- Prebuilt Parts page calls it after editing a bill of materials -- so
-- staff keep it and everyone else loses it. It rewrites stock_status on
-- the prebuilt machines, which is not something a shopper should be able
-- to set off at will.
REVOKE EXECUTE ON FUNCTION public.recompute_prebuilt_stock(integer[])
  FROM public, anon;
GRANT EXECUTE ON FUNCTION public.recompute_prebuilt_stock(integer[])
  TO authenticated;

-- The two SECURITY DEFINER views the Advisor reports as errors --
-- admin_dashboard and admin_products -- are deliberate and stay as they
-- are. They exist to show cost_price and stock_qty, which are revoked
-- from every client role precisely so a shopper cannot read the shop's
-- margins; a security_invoker view could not read them either. Both
-- carry WHERE (SELECT public.is_admin()), so a non-admin selecting from
-- them gets zero rows rather than a refusal. The reason for the finding
-- is the mechanism, and the mechanism is the point. Anon is revoked from
-- both so the only callers are signed-in accounts that then have to pass
-- is_admin().
REVOKE ALL ON public.admin_dashboard FROM anon;
REVOKE ALL ON public.admin_products  FROM anon;
GRANT SELECT ON public.admin_dashboard TO authenticated;
GRANT SELECT ON public.admin_products  TO authenticated;

-- Stop the default from re-arming itself. Supabase grants EXECUTE to
-- anon and authenticated on every function created in public; without
-- this, the next migration to add one reopens exactly the hole section 4
-- just closed, and nobody notices until the Advisor is read again.
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  REVOKE EXECUTE ON FUNCTIONS FROM anon;

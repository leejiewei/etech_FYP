-- ============================================================
-- Stop anyone writing whatever they like into the behaviour tables.
--
-- POLICIES AND GRANTS ONLY. No table is created, dropped or altered, no
-- column is added or removed, and no row is touched. Everything here is
-- a rule about who may write what, and every line reverses with the
-- opposite statement.
--
-- ------------------------------------------------------------
-- WHAT WAS WRONG
--
-- events, chatbot_logs and search_logs each carry an INSERT policy
-- granted to anon, because the shop front records what a signed-out
-- visitor does and that is the whole point of the beta. Each policy
-- checked one thing:
--
--     customer_id IS NULL OR customer_id = current_customer_id()
--
-- which stops somebody filing their activity under another customer's
-- id, and stops nothing else. In particular it says nothing about
-- event_type, and anon holds INSERT on that column. The enum is
-- ('view', 'cart_add', 'wishlist_add', 'purchase'), so anybody holding
-- the publishable key -- which ships inside web/js/config.js and inside
-- the APK, by design -- could post:
--
--     { product_id: 2011, event_type: 'purchase', created_at: '2026-01-01' }
--
-- as many times as they liked, for any product, dated to any moment.
--
-- Two things break when they do.
--
--   * The Inventory Velocity score is (views x1) + (cart adds x3) +
--     (purchases x5). Forged purchases move it five times faster than
--     forged views, so the admin dashboard's ranking becomes whatever
--     the last person with curl decided it should be.
--
--   * More seriously, events IS the Objective 1 dataset. Rows forged
--     during the beta are indistinguishable from real ones afterwards --
--     there is no signal that separates them -- so a polluted table is
--     not a corrupted report, it is a corrupted result with no way back.
--
-- The comment at the top of web/js/tracking.js said cart adds and
-- purchases "are recorded inside the database ... so they cannot be
-- faked from the browser". That was true of cart_add() and place_order()
-- and false of the events table itself. It is corrected in the same
-- commit as this file.
--
-- ------------------------------------------------------------
-- WHAT IT IS NOW
--
-- The clients only ever write one kind of row each, and now that is all
-- the policy permits:
--
--   events        event_type = 'view', and nothing else
--   chatbot_logs  a question and an answer, both length-capped
--   search_logs   a query and a count, capped and non-negative
--
-- cart_add, wishlist_add and purchase rows keep arriving, from
-- cart_add(), toggle_wishlist() and place_order(). Those are SECURITY
-- DEFINER functions and run as their owner, so they are not subject to
-- these policies at all and need no exception written for them. That is
-- the whole design: the three event types that mean something are
-- written by the database when the thing actually happens, and the one
-- that cannot be verified is the only one a client may assert.
--
-- The length caps live in the policy rather than in a CHECK constraint
-- deliberately -- a constraint is a schema change, and this file is not
-- allowed to be one. They are generous: 1000 characters is the same cap
-- the chat-advisor function applies to a question.
-- ============================================================


-- ---------------------------------------------------- events
DROP POLICY IF EXISTS "anyone may record activity" ON public.events;

CREATE POLICY "anyone may record a view" ON public.events
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    -- Unchanged: file it under yourself or under nobody.
    (customer_id IS NULL OR customer_id = (SELECT public.current_customer_id()))
    -- New, and the point of this migration.
    AND event_type = 'view'
  );

-- Nothing in either client sets these. web/js/tracking.js sends
-- (customer_id, anon_id, source, product_id, event_type) and
-- mobile/lib/services/shop.dart sends exactly the same five.
--
-- created_at defaults to now(), and letting a client override it means
-- letting it place a row anywhere in history -- which breaks the
-- forecast page, the monthly reports, and any session reconstruction the
-- Objective 1 analysis does.
--
-- event_id is GENERATED BY DEFAULT rather than ALWAYS, so a client can
-- supply its own and collide with the sequence. search_logs.search_id is
-- already ALWAYS and needs none of this; events and chatbot_logs were
-- written before that habit settled.
-- The broad grant has to come off before the narrow one goes on: a
-- table-level GRANT INSERT beats any column-level REVOKE, so revoking
-- the two columns on their own does nothing at all while the table-level
-- grant stands. 20260827114650_client_privileges.sql learned this the
-- same way for SELECT; it applies to INSERT identically.
REVOKE INSERT ON public.events FROM anon, authenticated;
GRANT  INSERT (customer_id, anon_id, source, product_id, event_type)
  ON public.events TO anon, authenticated;


-- ---------------------------------------------------- chatbot_logs
DROP POLICY IF EXISTS "anyone may log a chat" ON public.chatbot_logs;

CREATE POLICY "anyone may log a chat" ON public.chatbot_logs
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    (customer_id IS NULL OR customer_id = (SELECT public.current_customer_id()))
    -- A conversation, not a way of storing arbitrary volumes of text in
    -- somebody else's database. The chat-advisor function already caps a
    -- question at 1000 characters before Gemini ever sees it; this is the
    -- same number, enforced where it cannot be skipped by not using the
    -- chatbot at all.
    AND question IS NOT NULL
    AND length(question) <= 1000
    AND (answer IS NULL OR length(answer) <= 4000)
  );

REVOKE INSERT ON public.chatbot_logs FROM anon, authenticated;
GRANT  INSERT (customer_id, anon_id, source, question, answer, was_build_request)
  ON public.chatbot_logs TO anon, authenticated;


-- ---------------------------------------------------- search_logs
DROP POLICY IF EXISTS "anyone may record a search" ON public.search_logs;

CREATE POLICY "anyone may record a search" ON public.search_logs
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    (customer_id IS NULL OR customer_id = (SELECT public.current_customer_id()))
    AND query IS NOT NULL
    AND length(query) <= 200
    -- A negative result count is not a search anyone performed, and a
    -- wildly large one would skew "what did people look for and not
    -- find", which is the most useful column in this table.
    AND (result_count IS NULL OR (result_count >= 0 AND result_count <= 100000))
  );

REVOKE INSERT ON public.search_logs FROM anon, authenticated;
GRANT  INSERT (customer_id, anon_id, source, query, result_count)
  ON public.search_logs TO anon, authenticated;


-- ============================================================
-- What this does NOT fix, recorded so it is not mistaken for fixed.
--
-- A visitor can still post any number of *genuine-looking* view rows for
-- any product. That is not closeable with a policy: a view is an
-- assertion by a client and there is nothing on the other end to check
-- it against. What is closeable is the difference in weight -- a forged
-- view now counts 1 towards the velocity score instead of 5, and cannot
-- be dated into the past. If the beta shows signs of automated noise,
-- the next step is a per-anon_id rate limit, which needs somewhere to
-- count and therefore a table.
--
-- claim_anon_activity(p_anon_id) still takes the anon_id from the
-- caller, so a signed-in user who learned another visitor's anon_id
-- could absorb that visitor's unclaimed rows. The function is otherwise
-- tight -- customer_id IS NULL is in every WHERE, and the target is
-- always current_customer_id() and never an argument -- so it cannot
-- take rows that already belong to somebody, nor give them to anyone but
-- the caller. anon_id is a v4 UUID and is not published anywhere, so
-- this is a note about dataset integrity rather than a live risk.
-- ============================================================

-- ============================================================
-- Powered by ASUS: machines customers built, shown off.
--
-- The shop already sells the parts and already knows which brand each
-- one is. What it has never had is the finished thing: somebody's build,
-- photographed, with the parts named. That is worth having for two
-- reasons that pull in the same direction -- it is the most persuasive
-- page a component shop can put up, and every tagged part is a link
-- straight back to something on the shelf.
--
-- Three decisions are worth stating up front.
--
-- THE BADGE IS NOT AN OPINION. is_asus_verified is not typed in by
-- anybody. It is worked out from the parts that were tagged, by a
-- trigger, every time the tags change: an ASUS or ROG component in the
-- build and the badge is there, none and it is not. A badge a member of
-- staff could grant by hand would be a badge that could be granted by
-- mistake, and one that would go on saying "ASUS Certified" after the
-- ASUS board was untagged.
--
-- NOTHING IS PUBLIC UNTIL SOMEBODY LOOKS AT IT. Customers submit; staff
-- approve. The gallery reads a view that only ever returns approved
-- rows, and the policy underneath it says the same thing, so a page that
-- forgot to filter would come back empty rather than publish a stranger's
-- photograph of their bedroom.
--
-- THE PARTS ARE ROWS, NOT TEXT. A tag is a foreign key to products, so
-- "he used the 9070 XT" is the same fact as the one on the product page
-- and clicking it can go there. Free text would have been quicker and
-- would have made the gallery a dead end.
-- ============================================================

CREATE TYPE public.showcase_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED');

CREATE TABLE public.rig_showcases (
  rig_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- The schema calls a person a customer everywhere else, so this does
  -- too. ON DELETE CASCADE: a deleted account takes its submissions with
  -- it, which is the only defensible answer under the PDPA notice this
  -- shop already shows.
  customer_id INTEGER NOT NULL REFERENCES public.customers(customer_id) ON DELETE CASCADE,

  title       VARCHAR(120) NOT NULL,
  description TEXT NULL,

  -- Public URLs in the rig-showcases bucket. An array rather than a
  -- child table: these are an ordered gallery of one submission and are
  -- never queried on their own, never joined to, and never counted --
  -- which is the case where a column is the honest shape and a table is
  -- ceremony.
  image_urls  TEXT[] NOT NULL DEFAULT '{}',

  -- Written by the trigger below, never by hand. See the note above.
  is_asus_verified SMALLINT NOT NULL DEFAULT 0 CHECK (is_asus_verified IN (0,1)),

  status      public.showcase_status NOT NULL DEFAULT 'PENDING',

  -- Why staff turned one down, shown back to the person who sent it.
  review_note TEXT NULL,

  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at TIMESTAMPTZ NULL,

  CONSTRAINT showcase_has_a_title CHECK (btrim(title) <> ''),
  CONSTRAINT showcase_has_a_picture CHECK (cardinality(image_urls) > 0)
);

CREATE INDEX idx_showcase_status   ON public.rig_showcases (status);
CREATE INDEX idx_showcase_customer ON public.rig_showcases (customer_id);


-- One row per part tagged in a build.
CREATE TABLE public.rig_showcase_parts (
  rig_id     INTEGER NOT NULL REFERENCES public.rig_showcases(rig_id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES public.products(product_id) ON DELETE CASCADE,
  PRIMARY KEY (rig_id, product_id)
);

CREATE INDEX idx_showcase_part_product ON public.rig_showcase_parts (product_id);


-- ============================================================
-- Working out the badge.
--
-- "ASUS hardware" is a prefix match and not a list of exact names, and
-- that is worth explaining because the obvious version is wrong here.
-- This shop does not carry a brand called "ASUS" and another called
-- "ROG". It carries three:
--
--     Asus          Asus ROG          Asus TUF
--
-- so `upper(b.name) IN ('ASUS','ROG')` would have matched the first and
-- silently missed the ROG and TUF boards -- which are exactly the parts
-- somebody putting an ASUS badge on their build has bought.
--
-- The ROG clause is kept for the day the shop carries ROG on its own,
-- and costs nothing until then.
--
-- The match is on the brand's name rather than on a hard-coded brand_id,
-- because ids are a fact about this particular database and the rule is
-- a fact about the shop.
-- ============================================================
CREATE OR REPLACE FUNCTION public.rig_uses_asus(p_rig_id integer)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.rig_showcase_parts rp
    JOIN public.products p ON p.product_id = rp.product_id
    JOIN public.brands   b ON b.brand_id   = p.brand_id
    WHERE rp.rig_id = p_rig_id
      AND (upper(b.name) LIKE 'ASUS%' OR upper(b.name) LIKE 'ROG%')
  );
$$;

CREATE OR REPLACE FUNCTION public.refresh_rig_asus_badge()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_rig integer := COALESCE(NEW.rig_id, OLD.rig_id);
BEGIN
  UPDATE public.rig_showcases
  SET is_asus_verified = CASE WHEN public.rig_uses_asus(v_rig) THEN 1 ELSE 0 END
  WHERE rig_id = v_rig;

  RETURN NULL; -- AFTER trigger; the row it returns is ignored
END;
$$;

CREATE TRIGGER rig_parts_set_badge
AFTER INSERT OR DELETE ON public.rig_showcase_parts
FOR EACH ROW EXECUTE FUNCTION public.refresh_rig_asus_badge();


-- ============================================================
-- Who may see and do what
-- ============================================================
ALTER TABLE public.rig_showcases      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rig_showcase_parts ENABLE ROW LEVEL SECURITY;

-- The gallery. Approved only, and to everybody including signed-out
-- visitors -- a showcase nobody can see without an account is not a
-- showcase.
CREATE POLICY "approved rigs are public" ON public.rig_showcases
  FOR SELECT TO anon, authenticated USING (status = 'APPROVED');

-- Somebody's own submissions, whatever state they are in, so they can
-- see that theirs is still waiting and read why one was turned down.
CREATE POLICY "customers read their own rigs" ON public.rig_showcases
  FOR SELECT TO authenticated
  USING (customer_id = (SELECT public.current_customer_id()));

CREATE POLICY "staff manage rigs" ON public.rig_showcases
  FOR ALL TO authenticated
  USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));

-- The parts of a rig anybody is allowed to see. Written as an EXISTS on
-- the parent rather than repeating the rule, so there is one definition
-- of "may see this rig" and the tags cannot disagree with it.
CREATE POLICY "parts follow their rig" ON public.rig_showcase_parts
  FOR SELECT TO anon, authenticated
  USING (EXISTS (
    SELECT 1 FROM public.rig_showcases r
    WHERE r.rig_id = rig_showcase_parts.rig_id
  ));

CREATE POLICY "staff manage rig parts" ON public.rig_showcase_parts
  FOR ALL TO authenticated
  USING ((SELECT public.is_admin())) WITH CHECK ((SELECT public.is_admin()));

-- Submitting goes through submit_rig_showcase() below, so neither table
-- needs INSERT for a customer. Supabase hands GRANT ALL to anon and
-- authenticated on every new table; these take back what was never
-- meant.
REVOKE ALL ON public.rig_showcases      FROM anon, authenticated;
REVOKE ALL ON public.rig_showcase_parts FROM anon, authenticated;
GRANT SELECT ON public.rig_showcases      TO anon, authenticated;
GRANT SELECT ON public.rig_showcase_parts TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.rig_showcases      TO authenticated;
GRANT INSERT, UPDATE, DELETE ON public.rig_showcase_parts TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.rig_showcases_rig_id_seq TO authenticated;


-- ============================================================
-- Somewhere to put the photographs.
--
-- Public to read, like product-images and unlike payment-receipts. This
-- is a gallery: the whole purpose is that anybody can look, and signing
-- every image on every page load would be a round trip per picture for
-- no gain.
--
-- The honest limitation, stated rather than glossed: an image belonging
-- to a submission still waiting for approval is reachable by anybody who
-- has its URL. Nothing links to it and the names carry a timestamp, so
-- it is not discoverable -- but it is not secret either. That is the
-- right trade for a picture somebody uploaded in order to have it
-- published; it would be the wrong trade for a bank receipt, which is
-- why that bucket is private.
--
-- Writes are the customer's own folder only, checked by the same folder
-- name rule the receipts bucket uses.
-- ============================================================
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'rig-showcases',
  'rig-showcases',
  true,
  5242880,
  ARRAY['image/jpeg', 'image/png', 'image/webp']
)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "rig photos are public" ON storage.objects
  FOR SELECT TO anon, authenticated
  USING (bucket_id = 'rig-showcases');

CREATE POLICY "customers add their own rig photos" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'rig-showcases'
    AND (storage.foldername(name))[1] = (SELECT public.current_customer_id())::text
  );

CREATE POLICY "staff remove rig photos" ON storage.objects
  FOR DELETE TO authenticated
  USING (bucket_id = 'rig-showcases' AND (SELECT public.is_admin()));


-- ============================================================
-- Submitting a build.
--
-- One call, because a submission is a rig and its tags together. Two
-- statements from a browser could land the first and lose the second,
-- and a rig with no parts tagged is exactly the rig the badge rule
-- cannot answer.
--
-- The customer id is read from the session on this side rather than
-- accepted as an argument, the tags are filtered down to products that
-- actually exist and are on sale, and the status is not an argument at
-- all -- a submission is PENDING and only staff move it.
-- ============================================================
CREATE OR REPLACE FUNCTION public.submit_rig_showcase(
  p_title       text,
  p_description text,
  p_image_urls  text[],
  p_product_ids integer[]
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_customer integer := public.current_customer_id();
  v_title    text    := btrim(COALESCE(p_title, ''));
  v_rig      integer;
BEGIN
  IF v_customer IS NULL THEN
    RAISE EXCEPTION 'Please log in first.' USING ERRCODE = '42501';
  END IF;

  IF v_title = '' THEN
    RAISE EXCEPTION 'Give your build a title.' USING ERRCODE = 'P0001';
  END IF;

  IF p_image_urls IS NULL OR cardinality(p_image_urls) = 0 THEN
    RAISE EXCEPTION 'Add at least one photo of the build.' USING ERRCODE = 'P0001';
  END IF;

  IF cardinality(p_image_urls) > 6 THEN
    RAISE EXCEPTION 'Six photos is the most a build can have.' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO public.rig_showcases
    (customer_id, title, description, image_urls)
  VALUES
    (v_customer, left(v_title, 120),
     NULLIF(btrim(COALESCE(p_description, '')), ''),
     p_image_urls)
  RETURNING rig_id INTO v_rig;

  -- The tags. A DISTINCT join against products drops duplicates and
  -- anything that is not a real, on-sale product, so a hand-edited
  -- request cannot put a made-up id into the gallery. The trigger on
  -- this table then sets the badge.
  INSERT INTO public.rig_showcase_parts (rig_id, product_id)
  SELECT DISTINCT v_rig, p.product_id
  FROM unnest(COALESCE(p_product_ids, ARRAY[]::integer[])) AS wanted(product_id)
  JOIN public.products p ON p.product_id = wanted.product_id AND p.is_active = 1;

  RETURN v_rig;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.submit_rig_showcase(text, text, text[], integer[])
  FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.submit_rig_showcase(text, text, text[], integer[])
  TO authenticated;


-- ============================================================
-- Staff deciding.
-- ============================================================
CREATE OR REPLACE FUNCTION public.admin_set_rig_status(
  p_rig_id integer,
  p_status public.showcase_status,
  p_note   text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NOT (SELECT public.is_admin()) THEN
    RAISE EXCEPTION 'Staff access only.' USING ERRCODE = '42501';
  END IF;

  UPDATE public.rig_showcases
  SET status      = p_status,
      review_note = NULLIF(btrim(COALESCE(p_note, '')), ''),
      reviewed_at = now()
  WHERE rig_id = p_rig_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'That submission no longer exists.' USING ERRCODE = 'P0001';
  END IF;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.admin_set_rig_status(integer, public.showcase_status, text)
  FROM public, anon;
GRANT  EXECUTE ON FUNCTION public.admin_set_rig_status(integer, public.showcase_status, text)
  TO authenticated;


-- ============================================================
-- The gallery.
--
-- Approved only, spelled out here as well as in the policy -- a
-- signed-in member of staff carries "staff manage rigs", which returns
-- every row, and without this WHERE the public gallery would show them
-- the pending queue as though it were published.
--
-- The builder is named by first name only. It is a shop window, not a
-- directory: "Wei Ming's Ryzen build" is friendly, and the full name of
-- somebody who submitted a photograph of their desk is more than the
-- page needs.
-- ============================================================
CREATE VIEW public.rig_gallery WITH (security_invoker = on) AS
SELECT
  r.rig_id,
  r.title,
  r.description,
  r.image_urls,
  r.is_asus_verified,
  r.created_at,
  split_part(c.name, ' ', 1) AS builder
FROM public.rig_showcases r
JOIN public.customers c ON c.customer_id = r.customer_id
WHERE r.status = 'APPROVED';

REVOKE ALL ON public.rig_gallery FROM anon, authenticated;
GRANT SELECT ON public.rig_gallery TO anon, authenticated;

-- The tagged parts, with enough of the product on them to draw a link
-- back to the shop. Joined to the gallery rather than to the table, so
-- the parts of an unapproved rig are not reachable through this.
CREATE VIEW public.rig_gallery_parts WITH (security_invoker = on) AS
SELECT
  rp.rig_id,
  p.product_id,
  p.name  AS product_name,
  p.price,
  b.name  AS brand
FROM public.rig_showcase_parts rp
JOIN public.rig_showcases r ON r.rig_id = rp.rig_id AND r.status = 'APPROVED'
JOIN public.products p ON p.product_id = rp.product_id
JOIN public.brands   b ON b.brand_id   = p.brand_id;

REVOKE ALL ON public.rig_gallery_parts FROM anon, authenticated;
GRANT SELECT ON public.rig_gallery_parts TO anon, authenticated;


-- ============================================================
-- The moderation queue.
-- ============================================================
CREATE VIEW public.admin_rig_showcases WITH (security_invoker = on) AS
SELECT
  r.rig_id,
  r.customer_id,
  r.title,
  r.description,
  r.image_urls,
  r.is_asus_verified,
  r.status,
  r.review_note,
  r.created_at,
  r.reviewed_at,
  c.name  AS customer_name,
  c.email AS customer_email,
  (SELECT count(*) FROM public.rig_showcase_parts rp WHERE rp.rig_id = r.rig_id)
    AS tagged_parts
FROM public.rig_showcases r
JOIN public.customers c ON c.customer_id = r.customer_id;

REVOKE ALL ON public.admin_rig_showcases FROM anon, authenticated;
GRANT SELECT ON public.admin_rig_showcases TO authenticated;
